#!/usr/bin/env python3
"""l10n 共享文案源生成器（ADR 0031：界面国际化）。

单一真值在仓库根 `l10n/*.toml`（一个功能区一个文件，schema 见 `l10n/README.md`）。
本脚本把它生成到两端各自的形态：

- `rust --out <path>`：Linux 前端 `build.rs` 构建期调用，产出静态 match 查找
  （`lookup(locale, key)` / `lookup_one`），运行时零解析；
- `resw --out-dir <dir>`：Windows 端 `Strings.zh.resw` / `Strings.en.resw`
  （标准 resx XML，条目名=key）+ `Strings.g.cs`（`Strings.T(key)` /
  `Strings.Tn(key, n)` 访问器），S6（#204）接线进工程。

门禁（决策 3 / 4）：
- 重复 key、缺 zh、key 名 / 字段名不合法 → 报错退出码 1（构建失败即门禁）；
- 缺 en → 仅告警（stderr 逐行 `[l10n] en 缺失：<key>`），不阻断；
  发版前必须清零（S7/#205 接 release-check 门禁）。

用法：
    python3 tools/l10n_gen.py rust --out <path>
    python3 tools/l10n_gen.py resw --out-dir <dir>
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from xml.sax.saxutils import escape

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_L10N_DIR = REPO_ROOT / "l10n"

# 与 l10n/README.md 的 schema 一字不差：key=「区.蛇形名」，段名全小写。
KEY_RE = re.compile(r"^[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+$")
ALLOWED_FIELDS = {"key", "zh", "en", "status", "en_one", "zh_one"}
ALLOWED_STATUS = {"done", "pending_en"}

# 生成的 Rust catalog 里的 locale 编号（l10n.rs 按此接线）。
LOCALE_ZH = 0
LOCALE_EN = 1


class L10nError(Exception):
    """致命校验错误：任何一条都让生成失败（= 构建失败）。"""


def warn(message: str) -> None:
    print(f"[l10n] {message}", file=sys.stderr)


@dataclass
class Entry:
    key: str
    zh: str
    en: str | None
    status: str
    en_one: str | None = None
    zh_one: str | None = None
    source: str = ""

    @property
    def has_plural(self) -> bool:
        """缺 en_one = 无复数（README schema；zh_one 不单独构成复数）。"""
        return self.en_one is not None


def load_entries(l10n_dir: Path) -> list[Entry]:
    """读 `l10n/*.toml` 并做全部构建期校验；返回按 key 排序的条目。"""
    files = sorted(l10n_dir.glob("*.toml"))
    if not files:
        raise L10nError(f"{l10n_dir} 下没有 *.toml 文案源（至少要有 shell.toml）")

    entries: list[Entry] = []
    seen: dict[str, str] = {}
    for path in files:
        with path.open("rb") as handle:
            document = tomllib.load(handle)
        raw_entries = document.get("entry", [])
        if not isinstance(raw_entries, list):
            raise L10nError(f"{path.name}：[[entry]] 必须是数组表")
        for index, raw in enumerate(raw_entries, start=1):
            location = f"{path.name} 第 {index} 条"
            if not isinstance(raw, dict):
                raise L10nError(f"{location}：条目必须是表（[[entry]]）")
            unknown = sorted(set(raw) - ALLOWED_FIELDS)
            if unknown:
                raise L10nError(
                    f"{location}：未知字段 {unknown}（只允许 {sorted(ALLOWED_FIELDS)}）"
                )
            key = raw.get("key")
            if not isinstance(key, str) or not key:
                raise L10nError(f"{location}：缺 key")
            if not KEY_RE.match(key):
                raise L10nError(f"{location}：key「{key}」不合法（要求「区.蛇形名」，全小写）")
            if key in seen:
                raise L10nError(f"{location}：重复 key「{key}」（先见于 {seen[key]}）")
            seen[key] = location
            zh = raw.get("zh")
            if not isinstance(zh, str) or not zh:
                raise L10nError(f"{location}：缺 zh（{key}；zh 是 source of truth）")
            for field in ("en", "en_one", "zh_one"):
                value = raw.get(field)
                if value is not None and not isinstance(value, str):
                    raise L10nError(f"{location}：{field} 必须是字符串（{key}）")
            en = raw.get("en")
            if en is None:
                warn(f"en 缺失：{key}")
            status = raw.get("status")
            if not isinstance(status, str) or not status:
                raise L10nError(f"{location}：缺 status（{key}；取值 {sorted(ALLOWED_STATUS)}）")
            if status not in ALLOWED_STATUS:
                raise L10nError(f"{location}：status「{status}」未知（{key}）")
            entries.append(
                Entry(
                    key=key,
                    zh=zh,
                    en=en,
                    status=status,
                    en_one=raw.get("en_one"),
                    zh_one=raw.get("zh_one"),
                    source=location,
                )
            )
    entries.sort(key=lambda entry: entry.key)
    for entry in entries:
        if entry.zh_one is not None and not entry.has_plural:
            warn(f"zh_one 无对应 en_one（缺 en_one = 无复数，按无复数处理）：{entry.key}")
    return entries


def rust_str(value: str) -> str:
    """Rust 字符串字面量转义。"""
    out = value.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return f'"{out}"'


def gen_rust(entries: list[Entry], out_path: Path) -> None:
    """产出静态 match catalog：locale 编号 + key → 文案，无运行时解析。"""
    lines = [
        "// @generated by tools/l10n_gen.py from l10n/*.toml —— 请勿手工编辑。",
        "// 生成失败 = 构建失败（ADR 0031 决策 3）；改文案请改仓库根 l10n/。",
        "",
        "/// locale 编号：中文。",
        f"pub const LANG_ZH: u8 = {LOCALE_ZH};",
        "",
        "/// locale 编号：英文。",
        f"pub const LANG_EN: u8 = {LOCALE_EN};",
        "",
        "/// catalog 条目数（生成期元信息，冒烟断言用）。",
        "#[allow(dead_code)]",
        f"pub const L10N_KEY_COUNT: usize = {len(entries)};",
        "",
        "/// 查一条文案；`locale` 取 [`LANG_ZH`] / [`LANG_EN`]，缺译文返回 `None`，",
        "/// 回落链由 `l10n::t` 完成（当前语言 → en → zh → key 本身）。",
        "pub fn lookup(locale: u8, key: &str) -> Option<&'static str> {",
        "    match (locale, key) {",
    ]
    for entry in entries:
        lines.append(f"        (LANG_ZH, {rust_str(entry.key)}) => Some({rust_str(entry.zh)}),")
        if entry.en is not None:
            lines.append(f"        (LANG_EN, {rust_str(entry.key)}) => Some({rust_str(entry.en)}),")
    lines += [
        "        _ => None,",
        "    }",
        "}",
        "",
        "/// 复数 one 形态（ADR 0031 决策 5：one/other 两态）。登记了 `en_one` 的",
        "/// key 才有对应分支；调用方取不到 one 时回退 `lookup` 的 other 形态。",
        # 机制先于消费：S1 没有复数条目、`l10n::t_n` 的真实调用点随 Lane B 接线，
        # 生成期不能让 dead_code / 空 match 的 lint 阻断构建。
        "#[allow(dead_code, clippy::match_single_binding)]",
        "pub fn lookup_one(locale: u8, key: &str) -> Option<&'static str> {",
        "    match (locale, key) {",
    ]
    for entry in entries:
        if entry.has_plural:
            one = entry.en_one
            assert one is not None  # has_plural 定义保证
            lines.append(f"        (LANG_EN, {rust_str(entry.key)}) => Some({rust_str(one)}),")
            zh_one = entry.zh_one if entry.zh_one is not None else entry.zh
            lines.append(f"        (LANG_ZH, {rust_str(entry.key)}) => Some({rust_str(zh_one)}),")
    lines += [
        "        _ => None,",
        "    }",
        "}",
        "",
    ]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")


RESW_HEADER = """<?xml version="1.0" encoding="utf-8"?>
<root>
  <resheader name="resmimetype">
    <value>text/microsoft-resx</value>
  </resheader>
  <resheader name="version">
    <value>2.0</value>
  </resheader>
  <resheader name="reader">
    <value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>
  </resheader>
  <resheader name="writer">
    <value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>
  </resheader>
"""

STRINGS_G_CS = r"""// <auto-generated/> 由 tools/l10n_gen.py 从 l10n/*.toml 生成 —— 请勿手工编辑。
// ADR 0031：文案单一真值在 l10n/，Windows 端经 RESW / ResourceLoader 消费。
#nullable enable
using System;
using Microsoft.Windows.ApplicationModel.Resources;
using Sqarvo.Windows.Localization;

namespace Sqarvo.Windows.L10n;

/// 界面文案访问器：`Strings.T("shell.menu.view_language")`。
internal static class Strings
{
    private static readonly ResourceManager Manager = new();
    private static readonly ResourceContext Active = CreateContext(LanguageService.Effective);
    private static readonly ResourceContext Chinese = CreateContext("zh");

    private static ResourceContext CreateContext(string language)
    {
        var context = Manager.CreateResourceContext();
        context.QualifierValues["Language"] = language == "zh" ? "zh-CN" : "en-US";
        return context;
    }

    private static string? Lookup(string key, ResourceContext context)
    {
        return Manager.MainResourceMap.TryGetValue("Strings/" + key.Replace('.', '/'), context)?.ValueAsString
            is { Length: > 0 } value ? value : null;
    }

    /// 取一条文案，按当前语言、中文、键名的顺序回落。
    public static string T(string key) => Lookup(key, Active) ?? Lookup(key, Chinese) ?? key;

    /// 单次扫描命名占位符，避免把参数文本再次解释成模板。
    public static string Tf(string key, params (string Name, object Value)[] args)
    {
        return System.Text.RegularExpressions.Regex.Replace(T(key), @"\{([a-zA-Z_][a-zA-Z0-9_]*)\}", match =>
        {
            foreach (var (name, value) in args)
            {
                if (name == match.Groups[1].Value)
                {
                    return Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture) ?? "";
                }
            }

            return match.Value;
        });
    }

    /// one/other 两态复数（ADR 0031 决策 5）：英文 n==1 优先 `<key>.one`，
    /// 缺 one 条目 = 该 key 无复数；中文恒用 `<key>`。
    public static string Tn(string key, long n)
    {
        if (n == 1 && LanguageService.Effective == "en")
        {
            if (Lookup(key + ".one", Active) is { } one)
            {
                return one;
            }
        }

        return T(key);
    }
}
"""


def resw_items(entries: list[Entry], locale: str) -> dict[str, str]:
    """一种 locale 的「条目名 → 文本」。条目名就是 key（复数 one 形态为 `<key>.one`）。

    en 缺失时用 zh 兜底：resw 是构建期产物，兜底等价于运行时回落链，并让
    「两种 locale 同 key 集」自检恒可判——不一致即生成器 bug。
    """
    items: dict[str, str] = {}
    for entry in entries:
        if locale == "zh":
            items[entry.key] = entry.zh
            if entry.has_plural:
                items[f"{entry.key}.one"] = entry.zh_one if entry.zh_one is not None else entry.zh
        else:
            items[entry.key] = entry.en if entry.en is not None else entry.zh
            if entry.has_plural:
                assert entry.en_one is not None
                items[f"{entry.key}.one"] = entry.en_one
    return items


def write_resw(path: Path, items: dict[str, str]) -> None:
    lines = [RESW_HEADER]
    for name in sorted(items):
        value = escape(items[name])
        lines.append(f'  <data name="{escape(name, {chr(34): "&quot;"})}" xml:space="preserve">')
        lines.append(f"    <value>{value}</value>")
        lines.append("  </data>")
    lines.append("</root>")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def gen_resw(entries: list[Entry], out_dir: Path, *, pri_layout: bool = False) -> None:
    zh_items = resw_items(entries, "zh")
    en_items = resw_items(entries, "en")
    # key 集合一致性自检：两端条目名必须同集合（漏条目 = 生成器 bug，直接失败）。
    if set(zh_items) != set(en_items):
        only_zh = sorted(set(zh_items) - set(en_items))
        only_en = sorted(set(en_items) - set(zh_items))
        raise L10nError(f"resw key 集不一致：仅 zh {only_zh}；仅 en {only_en}")
    out_dir.mkdir(parents=True, exist_ok=True)
    accessor = STRINGS_G_CS
    if pri_layout:
        # PRI 把点当作映射层级；用键名语法不允许的连字符避免与复数键冲突。
        zh_items = {key.replace(".", "-"): value for key, value in zh_items.items()}
        en_items = {key.replace(".", "-"): value for key, value in en_items.items()}
        accessor = accessor.replace("key.Replace('.', '/')", "key.Replace('.', '-')")
    write_resw(out_dir / "Strings.zh.resw", zh_items)
    write_resw(out_dir / "Strings.en.resw", en_items)
    (out_dir / "Strings.g.cs").write_text(accessor, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="从仓库根 l10n/*.toml 生成两端文案 catalog（ADR 0031）"
    )
    parser.add_argument(
        "--l10n-dir",
        type=Path,
        default=DEFAULT_L10N_DIR,
        help="文案源目录（默认：仓库根 l10n/）",
    )
    sub = parser.add_subparsers(dest="command", required=True)
    rust = sub.add_parser("rust", help="生成 Linux Rust catalog")
    rust.add_argument("--out", type=Path, required=True, help="输出 .rs 路径（build.rs 传 OUT_DIR）")
    resw = sub.add_parser("resw", help="生成 Windows resw + Strings.g.cs")
    resw.add_argument("--out-dir", type=Path, required=True, help="输出目录")
    resw.add_argument("--pri-layout", action="store_true", help="使用 PRI 安全的资源名")
    args = parser.parse_args(argv)

    try:
        entries = load_entries(args.l10n_dir)
        if args.command == "rust":
            gen_rust(entries, args.out)
        elif args.command == "resw":
            gen_resw(entries, args.out_dir, pri_layout=args.pri_layout)
        else:  # argparse 已挡；防御用
            raise AssertionError(args.command)
    except L10nError as error:
        print(f"[l10n] {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
